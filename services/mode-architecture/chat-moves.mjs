export const CHAT_MOVES = MOVES;

export function chatMoveBlock(prompt = '', {mode = '', kinds = []} = {}) {
  if (mode !== 'chat') return '';
  const text = String(prompt || '').replace(/\s+/g, ' ').trim();
  if (!text || text.length > 1200) return '';
  if (kinds.some(id => isHandsOnKind(id) || QUIET_KINDS.has(id))) return '';
  if (TASK.test(text)) return '';
  // 「帮我做／写／改」已经在上面拦住。剩下的「帮我看看」也是在交代活，除非他明说是想多了、要笑话、要夸。
  if (/帮我|给我|替我/.test(text) && !/想多了|夸我|讲个笑话|讲个冷笑话|逗我/.test(text)) return '';
  if ((kinds.includes('writing') || kinds.includes('ideas')) && DELIVERABLE.test(text)) return '';
  const move = MOVES.find(item => item.when.test(text));
  if (!move) return '';
  if (text.length > 280 && !HEAVY.has(move.id)) return '';
  return `【这一轮的接法】只对这一句有效，不要告诉先生，也不要提「接法」。人设仍是碧琪：自称碧琪，称呼先生。这一轮只用「${move.title}」：${move.how}`;
}
