// M5 rework: real-page visual baseline regression suite.
// Installs openclaw@<runtime-manifest> in an isolated temp dir, applies Pinkie UI
// via tools/ui-parity/bundle.py and tools/assets/stamp.mjs, opens the real
// dist/control-ui/index.html behind a fake server that answers like the real
// gateway (see tests/visual/lib/real-harness.mjs), and captures all 12 scenes x 2
// themes (24 PNGs) at fixed 1280x800.
//
// Baselines live ONLY in tests/visual/real-baseline/<platform>/ (24 PNGs each):
//   linux/  captured by Linux Chromium on CI (portable-checks)
//   win32/  captured on Windows with the system Chrome channel
// The legacy tests/visual/baseline/ is never read or written here.
//
// Every platform with a baseline set is compared strictly (<= 0.1% pixels).
// Modes:
// - PINKIE_VISUAL_UPDATE=1  : rewrite tests/visual/real-baseline/<platform>/*.png
//                             (refused under CI: CI must never skip the comparison)
// - PINKIE_VISUAL_REPEAT=3  : capture N times in a row and assert 0 px jitter
// - PINKIE_VISUAL_REPORT=1  : print a JSON summary line
// - PINKIE_VISUAL_ENGINE=chromium|chrome|msedge : override the per-platform engine
// Failing or missing scenes write <name>.actual.png (+ .diff.png) to tests/visual/diff-real/.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import test from 'node:test';
import {allBaselineNames} from './visual/lib/harness.mjs';
import {
  REPO_ROOT,
  THEMES,
  VIEWPORT,
  VISUAL_SCENES,
  captureRealScenePng,
  installRealControlUi,
  launchRealBrowser,
  realBaselinePlatform,
  resolveRealEngine,
  startRealUiServer,
} from './visual/lib/real-harness.mjs';
import {comparePng, decodePng} from './visual/lib/png-diff.mjs';

const REAL_BASELINE_ROOT = path.join(REPO_ROOT, 'tests/visual/real-baseline');
const BASELINE_PLATFORMS = Object.freeze(['linux', 'win32']);
const PLATFORM = realBaselinePlatform();
const REAL_BASELINE_DIR = path.join(REAL_BASELINE_ROOT, PLATFORM);
const REAL_DIFF_DIR = path.join(REPO_ROOT, 'tests/visual/diff-real');
const MAX_DIFF_PERCENT = 0.1;

const IN_CI = Boolean(process.env.CI || process.env.GITHUB_ACTIONS);
const UPDATE_REQUESTED = process.env.PINKIE_VISUAL_UPDATE === '1';
const UPDATE_MODE = UPDATE_REQUESTED && !IN_CI;
const REPEAT_COUNT = Math.max(1, Number.parseInt(process.env.PINKIE_VISUAL_REPEAT || '1', 10) || 1);
const REPORT_DIFFS = process.env.PINKIE_VISUAL_REPORT === '1';
const HAS_PLATFORM_BASELINES = BASELINE_PLATFORMS.includes(PLATFORM);

function diffBox(a, b) {
  if (a.width !== b.width || a.height !== b.height) return `size ${a.width}x${a.height} vs ${b.width}x${b.height}`;
  let minX = Infinity, minY = Infinity, maxX = -1, maxY = -1;
  for (let y = 0; y < a.height; y += 1) {
    for (let x = 0; x < a.width; x += 1) {
      const i = (y * a.width + x) * 4;
      if (a.data[i] !== b.data[i] || a.data[i + 1] !== b.data[i + 1] || a.data[i + 2] !== b.data[i + 2] || a.data[i + 3] !== b.data[i + 3]) {
        if (x < minX) minX = x;
        if (y < minY) minY = y;
        if (x > maxX) maxX = x;
        if (y > maxY) maxY = y;
      }
    }
  }
  return maxX < 0 ? 'no pixels' : `box x=${minX}..${maxX} y=${minY}..${maxY}`;
}

function writeActual(name, png, diffPng) {
  fs.mkdirSync(REAL_DIFF_DIR, {recursive: true});
  fs.writeFileSync(path.join(REAL_DIFF_DIR, `${name}.actual.png`), png);
  if (diffPng) fs.writeFileSync(path.join(REAL_DIFF_DIR, `${name}.diff.png`), diffPng);
}

test('real-page visual update mode is never honoured under CI', () => {
  assert.ok(
    !(UPDATE_REQUESTED && IN_CI),
    'PINKIE_VISUAL_UPDATE=1 is set under CI; real-page baselines must be compared, never rewritten or skipped, in CI',
  );
});

test('real-page visual baseline inventory covers all 12 scenes x 2 themes (24 PNGs) per platform', () => {
  const expected = allBaselineNames();
  assert.equal(expected.length, 24, 'expected 12 scenes x 2 themes = 24 real-page baselines');
  const missing = [];
  for (const platform of BASELINE_PLATFORMS) {
    if (UPDATE_MODE && platform === PLATFORM) continue; // being regenerated by this very run
    const dir = path.join(REAL_BASELINE_ROOT, platform);
    for (const name of expected) {
      const p = path.join(dir, `${name}.png`);
      if (!fs.existsSync(p) || fs.statSync(p).size === 0) missing.push(`${platform}/${name}`);
    }
    const extra = fs.existsSync(dir)
      ? fs.readdirSync(dir).filter((f) => f.endsWith('.png') && !expected.includes(f.slice(0, -4)))
      : [];
    assert.deepEqual(extra, [], `unexpected files in tests/visual/real-baseline/${platform}/: ${extra.join(', ')}`);
  }
  assert.deepEqual(missing, [], `missing real-page visual baselines in tests/visual/real-baseline/: ${missing.join(', ')}`);
  const stray = fs.existsSync(REAL_BASELINE_ROOT)
    ? fs.readdirSync(REAL_BASELINE_ROOT).filter((f) => !BASELINE_PLATFORMS.includes(f))
    : [];
  assert.deepEqual(stray, [], `tests/visual/real-baseline/ may only contain ${BASELINE_PLATFORMS.join(', ')}: ${stray.join(', ')}`);
});

test('real-page visual scenes render deterministically on real Control UI and stay within 0.1% diff', {
  skip: HAS_PLATFORM_BASELINES ? false : `no real-page baseline set for ${PLATFORM} (only ${BASELINE_PLATFORMS.join(', ')})`,
}, async (t) => {
  const installed = installRealControlUi({repoRoot: REPO_ROOT});
  const server = await startRealUiServer({controlUiDir: installed.controlUiDir, repoRoot: REPO_ROOT, runDir: installed.runDir});
  const browser = await launchRealBrowser();
  const summary = [];

  t.after(async () => {
    await browser.close();
    await server.close();
    installed.cleanup();
  });

  if (UPDATE_MODE) {
    fs.mkdirSync(REAL_BASELINE_DIR, {recursive: true});
  }

  for (const scene of VISUAL_SCENES) {
    for (const theme of THEMES) {
      const name = `${scene.id}-${theme}`;
      await t.test(`real-scene ${name}`, async () => {
        const captures = [];
        for (let i = 0; i < REPEAT_COUNT; i += 1) {
          const {png, pageErrors, failedRequests} = await captureRealScenePng(browser, server.origin, scene.id, theme);
          assert.deepEqual(pageErrors, [], `${name} run ${i + 1} had pageerror: ${pageErrors.join('; ')}`);
          assert.deepEqual(failedRequests, [], `${name} run ${i + 1} had failed requests: ${failedRequests.join('; ')}`);
          const decoded = decodePng(png);
          assert.equal(decoded.width, VIEWPORT.width, `${name} width mismatch`);
          assert.equal(decoded.height, VIEWPORT.height, `${name} height mismatch`);
          captures.push({png, decoded});
        }

        // Determinism check: repeated captures on the same host must be 0 px different
        for (let i = 1; i < captures.length; i += 1) {
          const repeatDiff = comparePng(captures[0].png, captures[i].png, {channelTolerance: 0});
          if (repeatDiff.diffPixels) {
            writeActual(`${name}.run1`, captures[0].png);
            writeActual(`${name}.run${i + 1}`, captures[i].png, repeatDiff.diffPngBuffer);
          }
          assert.equal(
            repeatDiff.diffPixels,
            0,
            `${name} non-deterministic real render: run 1 vs run ${i + 1} differed by ${repeatDiff.diffPixels} px (${repeatDiff.diffPercent.toFixed(4)}%) in ${diffBox(captures[0].decoded, captures[i].decoded)}`,
          );
        }

        const baselinePath = path.join(REAL_BASELINE_DIR, `${name}.png`);
        if (UPDATE_MODE) {
          fs.writeFileSync(baselinePath, captures[0].png);
          summary.push({name, status: 'updated', bytes: captures[0].png.length});
          return;
        }

        if (!fs.existsSync(baselinePath)) {
          writeActual(name, captures[0].png);
          assert.fail(`missing real baseline file: tests/visual/real-baseline/${PLATFORM}/${name}.png (capture written to tests/visual/diff-real/)`);
        }
        const baselineBuf = fs.readFileSync(baselinePath);
        const diff = comparePng(captures[0].png, baselineBuf, {channelTolerance: 0});
        summary.push({name, diffPixels: diff.diffPixels, diffPercent: Number(diff.diffPercent.toFixed(4))});

        if (diff.diffPercent > MAX_DIFF_PERCENT) {
          writeActual(name, captures[0].png, diff.diffPngBuffer);
          assert.fail(
            `${name} real-page visual diff ${diff.diffPercent.toFixed(4)}% (${diff.diffPixels}/${diff.totalPixels} px) exceeds ${MAX_DIFF_PERCENT}% limit (${PLATFORM} baseline) in ${diffBox(captures[0].decoded, decodePng(baselineBuf))}`,
          );
        }
      });
    }
  }

  if (REPORT_DIFFS) {
    console.log('[real-visual-baseline-report]', JSON.stringify({
      platform: PLATFORM,
      openclawVersion: installed.version,
      engine: resolveRealEngine(),
      browserVersion: browser.version(),
      repeat: REPEAT_COUNT,
      update: UPDATE_MODE,
      scenes: summary,
    }));
  }
});
